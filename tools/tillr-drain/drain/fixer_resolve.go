// FixerProvedKind records a trunk fixer resolved by a green heavy proof: the proved
// commit, its proof time and the fixer's checks the proof passed. It is the evidence an
// acquittal waiting on that fixer is released by (repairedTrunkWaiter).
const FixerProvedKind = "drain.fixer-proved"

func init() {
	if err := event.Register(FixerProvedKind, Utility); err != nil {
		panic(err)
	}
}

// fixerProof is the payload of FixerProvedKind.
type fixerProof struct {
	FixerItem string   `json:"fixer_item"`
	Green     string   `json:"green"`
	ProvedAt  string   `json:"proved_at"`
	Checks    []string `json:"checks"`
}

// generatedTriageNote is appended to a triage conflict a generated item was wrongly given.
const generatedTriageNote = "This item is generated by the loop or by sync and needs no document block of its own; triage does not apply, so the item returns to its worker."

// gateBudgetCloseReason is why the loop closes a gate-budget item an older build filed.
const gateBudgetCloseReason = "A gate budget is a reported target, never a hold or an item: an overrun is reported in the loop's log and on the board's gate trend, and the loop no longer files an item for it."

// releaseGeneratedTriage undoes the triage hold a generated item (IsGeneratedItem)
// received when document-fed triage still treated it as an undeclared request. Its triage
// conflict is closed and the item goes back in the queue; nothing in it was the owner's to
// answer. A gate-budget item, the overrun alarm an older build filed, is closed instead:
// the budget is a reported target, so there is nothing for it to do.
func (l *Loop) releaseGeneratedTriage(ctx context.Context) error {
	s, err := store.Open(ctx, l.cfg.Store, true)
	if err != nil {
		return err
	}
	defer s.Close()
	pending := func(r *store.Reader) ([]item.Conflict, []string, error) {
		conflicts, err := item.ReadConflicts(r)
		if err != nil {
			return nil, nil, err
		}
		out := []item.Conflict{}
		for id, c := range conflicts {
			if !IsGeneratedItem(id) || c.TriageVersion == "" || c.Status == "closed" || c.Status == "answered" {
				continue
			}
			var state string
			if err := r.QueryRow(`SELECT state FROM items WHERE item_id=?`, id).Scan(&state); err != nil {
				if errors.Is(err, sql.ErrNoRows) {
					continue
				}
				return nil, nil, err
			}
			if state == StateBlocked {
				out = append(out, c)
			}
		}
		sort.Slice(out, func(i, j int) bool { return out[i].ItemID < out[j].ItemID })
		rec, err := definition.ForReader(r)
		if err != nil {
			return nil, nil, err
		}
		def := rec.Parsed
		rows, err := r.Query(`SELECT item_id, state FROM items WHERE item_id LIKE ? ORDER BY item_id`, GateBudgetItemPrefix+"%")
		if err != nil {
			return nil, nil, err
		}
		defer rows.Close()
		alarms := []string{}
		for rows.Next() {
			var id, state string
			if err := rows.Scan(&id, &state); err != nil {
				return nil, nil, err
			}
			if IsGateBudgetItem(id) && !finishedState(def, state) && state != def.Closed {
				alarms = append(alarms, id)
			}
		}
		return out, alarms, rows.Err()
	}
	var found []item.Conflict
	var alarms []string
	if err := s.ReadTx(ctx, func(r *store.Reader) error {
		found, alarms, err = pending(r)
		return err
	}); err != nil || len(found)+len(alarms) == 0 {
		return err
	}
	return s.WriteTx(ctx, func(tx *store.Tx) error {
		found, alarms, err := pending(tx.Reader())
		if err != nil {
			return err
		}
		at := l.cfg.Now().UTC()
		for _, c := range found {
			c.Status, c.WaitingOn = "closed", "build"
			if c.RunID == "" {
				c.RunID = c.DesignRunID
			}
			c.Text = strings.TrimSpace(c.Text) + "\n" + generatedTriageNote
			if err := item.RecordConflict(tx, c, at); err != nil {
				return err
			}
			l.reportf("loop: %s triage conflict %s closed: %s\n", c.ItemID, c.ConflictID, generatedTriageNote)
		}
		for _, id := range alarms {
			if _, err := item.Close(ctx, tx, id, gateBudgetCloseReason, "tillr-drain", at); err != nil {
				return err
			}
			l.reportf("loop: closed gate-budget item %s: %s\n", id, gateBudgetCloseReason)
		}
		return nil
	})
}

// readGreenProof answers the heavy runner's green pointer and its recorded proof, or a
// zero proof when there is no pointer or no proof for it.
func readGreenProof(ctx context.Context, root string) (heavy.GreenProof, error) {
	green, err := heavyGreen(ctx, root)
	if err != nil || green == "" {
		return heavy.GreenProof{}, err
	}
	dir, err := heavyDirectory(ctx, root)
	if err != nil {
		return heavy.GreenProof{}, err
	}
	return readGreenProofFile(dir, green)
}

// readGreenProofFile reads the record for an exact commit, even after the green pointer
// has advanced. The caller supplies a full commit SHA, not a ref or path.
func readGreenProofFile(dir, sha string) (heavy.GreenProof, error) {
	raw, err := os.ReadFile(filepath.Join(dir, "green-"+sha+".json"))
	if os.IsNotExist(err) {
		return heavy.GreenProof{}, nil
	}
	if err != nil {
		return heavy.GreenProof{}, err
	}
	var proof heavy.GreenProof
	if err := json.Unmarshal(raw, &proof); err != nil {
		return heavy.GreenProof{}, err
	}
	if proof.Commit != sha {
		return heavy.GreenProof{}, nil
	}
	return proof, nil
}

// resolveCommit answers the full sha a fixer id's short sha names, or "" when the
// repository holds no such commit.
func resolveCommit(ctx context.Context, root, sha string) (string, error) {
	cmd := exec.CommandContext(ctx, "git", "-C", root, "rev-parse", "--verify", "--quiet", sha+"^{commit}")
	out, err := cmd.Output()
	if err == nil {
		return strings.TrimSpace(string(out)), nil
	}
	var exit *exec.ExitError
	if errors.As(err, &exit) && exit.ExitCode() == 1 {
		return "", nil
	}
	return "", Externalf("resolving fixer commit %s: %v", sha, err)
}

// provedFixer is one open fixer a proof covers, and the proof that covers it.
type provedFixer struct {
	id       string
	seen     int64
	checks   []string
	proof    checkProof
	finished bool
	keepLive bool
}

// provableChecks is the checks a proof must have passed to cover a fixer. A fixer can
// name a check twice: by its kind (`tillr-docs`, the selector a replay accepts) and by
// its labelled id (`tillr-docs/every-face-...`), which is the only spelling a proof
// records. A bare kind is answered by the labelled checks of that kind the fixer also
// names; a bare kind with none stays a check of its own.
func provableChecks(checks []string) []string {
	out := []string{}
	for _, check := range checks {
		labelled := false
		if !strings.Contains(check, "/") {
			for _, other := range checks {
				labelled = labelled || strings.HasPrefix(other, check+"/")
			}
		}
		if !labelled {
			out = append(out, check)
		}
	}
	return out
}

// awaitedFixers answers the trunk fixers some blocked item waits on as a
// trunk-already-red acquittal.
func awaitedFixers(r *store.Reader) (map[string]bool, error) {
	rows, err := r.Query(`SELECT item_id FROM items WHERE state=?`, StateBlocked)
	if err != nil {
		return nil, err
	}
	ids := []string{}
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			rows.Close()
			return nil, err
		}
		ids = append(ids, id)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return nil, err
	}
	awaited := map[string]bool{}
	for _, id := range ids {
		waiting, _, err := item.ReadWaitingOn(r, id)
		if err != nil {
			return nil, err
		}
		if waiting == nil {
			continue
		}
		if fixer := strings.TrimPrefix(waiting.Waiter, "item:"); fixer != waiting.Waiter && IsTrunkFixer(fixer) {
			awaited[fixer] = true
		}
	}
	return awaited, nil
}

// checkProof is one commit's recorded passes, by check, each with the time it passed.
// The green proof is a whole run's (every check it names passed at its proof time). The
// tip run's progress is a run still going, or red for some other check: its passes are
// proof for exactly the checks they name, which is what lets a fixer whose named check
// already passes on the tip end without waiting for a whole green run.
type checkProof struct {
	commit   string
	at       map[string]time.Time
	whole    bool
	provedAt time.Time
}

// passed answers whether every named check passed in this proof after seen (unix ms).
// A partial proof never covers a fixer that names no check.
func (p checkProof) passed(checks []string, seen int64) bool {
	if p.whole && p.provedAt.UnixMilli() <= seen {
		return false
	}
	if !p.whole && len(checks) == 0 {
		return false
	}
	for _, check := range checks {
		if at, ok := p.at[check]; ok && at.UnixMilli() > seen {
			continue
		}
		if p.whole && !strings.Contains(check, "/") {
			matched := false
			prefix := check + "/"
			for k, at := range p.at {
				if strings.HasPrefix(k, prefix) && at.UnixMilli() > seen {
					matched = true
					break
				}
			}
			if matched {
				continue
			}
		}
		return false
	}
	return true
}

// proofPastRed answers whether proofCommit is at or past red on the trunk. On an
// unrewritten trunk (or one whose rewrite is in trunk_rewrites), containsCommit answers
// directly. When the trunk was rewritten off red without a trunk_rewrites row (for
// instance, an earlier accept-rewrite onto a moved base), red's patch-matched commit on
// the trunk must be an ancestor of proofCommit; if red was dropped or amended off an
// accepted trunk, proofCommit must contain their merge base.
func proofPastRed(ctx context.Context, root, lost, red, proofCommit string) (bool, error) {
	ok, err := containsCommit(ctx, root, red, proofCommit)
	if err != nil || ok {
		return ok, err
	}
	onTrunk, err := containsCommit(ctx, root, red, TrunkRef)
	if err != nil || onTrunk {
		return false, err
	}
	proofOnTrunk, err := containsCommit(ctx, root, proofCommit, TrunkRef)
	if err != nil || !proofOnTrunk {
		return false, err
	}
	out, err := gather(ctx, gitKey("past-red", root, []string{red, proofCommit, lost}), func(ctx context.Context) (string, error) {
		_, oldIDs, err := patchIDs(ctx, root, TrunkRef+".."+red)
		if err != nil {
			return "", err
		}
		newCommits, newIDs, err := patchIDs(ctx, root, red+".."+TrunkRef)
		if err != nil {
			return "", err
		}
		if id := oldIDs[red]; id != "" {
			for _, c := range newCommits {
				if newIDs[c] == id {
					yes, err := trunkAncestor(ctx, root, c, proofCommit)
					if err != nil || !yes {
						return "no", err
					}
					return "yes", nil
				}
			}
		}
		if lost != "" {
			return "no", nil
		}
		mb, err := rawGit(ctx, root, nil, "merge-base", red, TrunkRef)
		if err != nil {
			return "no", nil
		}
		yes, err := trunkAncestor(ctx, root, strings.TrimSpace(mb), proofCommit)
		if err != nil || !yes {
			return "no", err
		}
		return "yes", nil
	})
	return out == "yes", err
}

// describe is the reason a fixer this proof covers is resolved with.
func (p checkProof) describe(checks []string) string {
	named := "no named check"
	if len(checks) > 0 {
		named = strings.Join(checks, ", ")
	}
	if p.whole {
		return "heavy proof green at " + p.commit + " (" + p.provedAt.UTC().Format("2006-01-02T15:04:05Z") + "), which contains the red commit and passed " + named
	}
	return "the heavy run of " + p.commit + ", which contains the red commit, passed " + named + " (" + p.provedAt.UTC().Format("2006-01-02T15:04:05Z") + "); the rest of that run is not needed to show this fixer's check repaired"
}

// readCheckProofs answers the green proof and the current tip run's recorded passes.
// The tip run's passes come from the runner's own progress record and the legacy
// program's, both keyed to the one tip they were judged on.
func readCheckProofs(ctx context.Context, root string) ([]checkProof, error) {
	proofs := []checkProof{}
	green, err := readGreenProof(ctx, root)
	if err != nil {
		return nil, err
	}
	if green.Commit != "" && !green.ProvedAt.IsZero() && green.Passed != nil {
		at := map[string]time.Time{}
		for _, id := range green.Passed {
			at[id] = green.ProvedAt
		}
		proofs = append(proofs, checkProof{commit: green.Commit, at: at, whole: true, provedAt: green.ProvedAt})
	}
	dir, err := heavyDirectory(ctx, root)
	if err != nil {
		return nil, err
	}
	progress, err := readProgressCheckProof(dir, "")
	if err != nil {
		return nil, err
	}
	if progress.commit != "" {
		proofs = append(proofs, progress)
	}
	return proofs, nil
}

// readProgressCheckProof reads the tip run's passes. When rev is set, ignore progress
// made on any other commit, including when native and legacy checks report different tips.
func readProgressCheckProof(dir, rev string) (checkProof, error) {
	tip, at := "", map[string]time.Time{}
	add := func(sha, id string, when time.Time) {
		if sha == "" || when.IsZero() || (rev != "" && sha != rev) || (tip != "" && sha != tip) {
			return
		}
		tip = sha
		if old, ok := at[id]; !ok || when.Before(old) {
			at[id] = when
		}
	}
	var progress heavyProgress
	if raw, err := os.ReadFile(filepath.Join(dir, "heavy-progress.json")); err == nil {
		if err := json.Unmarshal(raw, &progress); err != nil {
			return checkProof{}, err
		}
		for id, check := range progress.Checks {
			if check.Result == "pass" {
				add(progress.TipSHA, id, progress.PassedAt[id])
			}
		}
	} else if !os.IsNotExist(err) {
		return checkProof{}, err
	}
	var legacy struct {
		TipSHA string `json:"tip_sha"`
		Checks map[string]struct {
			ProvedAt string `json:"proved_at"`
		} `json:"checks"`
	}
	if raw, err := os.ReadFile(filepath.Join(dir, "heavy-legacy-progress.json")); err == nil {
		if err := json.Unmarshal(raw, &legacy); err != nil {
			return checkProof{}, err
		}
		for id, check := range legacy.Checks {
			if when, err := time.Parse(time.RFC3339, check.ProvedAt); err == nil {
				add(legacy.TipSHA, id, when)
			}
		}
	} else if !os.IsNotExist(err) {
		return checkProof{}, err
	}
	latest := time.Time{}
	for _, when := range at {
		if when.After(latest) {
			latest = when
		}
	}
	return checkProof{commit: tip, at: at, provedAt: latest}, nil
}

// resolveProvedFixers settles every open trunk fixer a recorded pass has made moot: the
// proved commit contains the fixer's red commit, and every check the fixer names passed on
// it after the fixer's last red observation. The proof is either a whole green run or the
// tip run's own passes of the fixer's checks, so a stale fixer — one whose check already
// passes on the tip — ends as soon as that check passes, not when a whole run is green.
// The fixer's own state does not matter — one parked on the owner is resolved the same
// way — because the trunk-broken hold it carries is about the trunk, and the proof shows
// its check green. An older proof that does not list its passed checks resolves nothing.
func (l *Loop) resolveProvedFixers(ctx context.Context) error {
	if l.cfg.Root == "" {
		return nil
	}
	registerRewriteStore(l.cfg.Root, l.cfg.Store)
	proofs, err := readCheckProofs(ctx, l.cfg.Root)
	if err != nil || len(proofs) == 0 {
		return err
	}
	s, err := store.Open(ctx, l.cfg.Store, true)
	if err != nil {
		return err
	}
	defer s.Close()
	type open struct {
		id, text string
		seen     int64
		// finished is a fixer someone closed (or another route ended) without a landing
		// while items are still acquitted behind it. A proof of its checks is recorded for
		// it, so those items are released (repairedTrunkWaiter); its state is not touched.
		finished bool
		keepLive bool
	}
	read := func(r *store.Reader) ([]open, error) {
		lifecycle, err := definition.ForReader(r)
		if err != nil {
			return nil, err
		}
		declared := lifecycle.Parsed
		awaited, err := awaitedFixers(r)
		if err != nil {
			return nil, err
		}
		rows, err := r.Query(`SELECT i.item_id, i.state, COALESCE(c.text, '') FROM items i LEFT JOIN item_criteria c ON c.item_id=i.item_id AND c.criterion_id='trunk-green' WHERE i.item_id LIKE 'fixer-main-%' ORDER BY i.item_id`)
		if err != nil {
			return nil, err
		}
		found := []open{}
		for rows.Next() {
			var o open
			var state string
			if err := rows.Scan(&o.id, &state, &o.text); err != nil {
				rows.Close()
				return nil, err
			}
			if !finishedState(declared, state) {
				found = append(found, o)
			} else if state != StateLanded && awaited[o.id] {
				o.finished = true
				found = append(found, o)
			}
		}
		rows.Close()
		if err := rows.Err(); err != nil {
			return nil, err
		}
		kept := found[:0]
		for _, o := range found {
			if o.finished {
				// Already proved: its waiters are released by that record.
				if proved, err := fixerProvedGreen(r, o.id); err != nil {
					return nil, err
				} else if proved != "" {
					continue
				}
			}
			kept = append(kept, o)
		}
		found = kept
		for i := range found {
			// The last red observation: the fixer's filing or a later red tip attached
			// to it. A proof recorded before it cannot speak for that observation.
			var seen sql.NullInt64
			if err := r.QueryRow(`SELECT MAX(ts) FROM events WHERE object_id=? AND kind IN (?, ?)`, found[i].id, item.AddKind, FixerAttachedKind).Scan(&seen); err != nil {
				return nil, err
			}
			found[i].seen = seen.Int64
			if !found[i].finished {
				keep, err := fixerKeepsLive(r, found[i].id)
				if err != nil {
					return nil, err
				}
				found[i].keepLive = keep
			}
		}
		return found, nil
	}
	var candidates []open
	var lost string
	if err := s.ReadTx(ctx, func(r *store.Reader) error {
		th, err := readTrunkHistory(r)
		if err != nil {
			return err
		}
		lost = th.Lost
		candidates, err = read(r)
		return err
	}); err != nil || len(candidates) == 0 {
		return err
	}
	covered := []provedFixer{}
	for _, o := range candidates {
		red, err := resolveCommit(ctx, l.cfg.Root, TrunkFixerSHA(o.id))
		if err != nil {
			return err
		}
		if red == "" {
			continue
		}
		checks := provableChecks(fixerChecks(o.text))
		for _, proof := range proofs {
			if !proof.passed(checks, o.seen) {
				continue
			}
			contains, err := proofPastRed(ctx, l.cfg.Root, lost, red, proof.commit)
			if err != nil {
				return err
			}
			if contains {
				covered = append(covered, provedFixer{id: o.id, seen: o.seen, checks: checks, proof: proof, finished: o.finished, keepLive: o.keepLive})
				break
			}
		}
	}
	if len(covered) == 0 {
		return nil
	}
	at := l.cfg.Now().UTC()
	return s.WriteTx(ctx, func(tx *store.Tx) error {
		lifecycle, err := definition.ForReader(tx.Reader())
		if err != nil {
			return err
		}
		declared := lifecycle.Parsed
		for _, f := range covered {
			var state string
			if err := tx.QueryRow(`SELECT state FROM items WHERE item_id=?`, f.id).Scan(&state); err != nil {
				return err
			}
			reason := f.proof.describe(f.checks)
			if f.finished {
				if state == StateLanded || !finishedState(declared, state) {
					continue
				}
				if proved, err := fixerProvedGreen(tx.Reader(), f.id); err != nil {
					return err
				} else if proved != "" {
					continue
				}
				if f.checks == nil {
					f.checks = []string{}
				}
				if err := appendEffect(tx, FixerProvedKind, f.id, fixerProof{FixerItem: f.id, Green: f.proof.commit, ProvedAt: f.proof.provedAt.UTC().Format("2006-01-02T15:04:05.000Z"), Checks: f.checks}, at); err != nil {
					return err
				}
				l.reportf("loop: %s is %s, and its checks now pass: %s; the items acquitted behind it are released\n", f.id, state, reason)
				continue
			}
			if finishedState(declared, state) {
				continue
			}
			keep, err := fixerKeepsLive(tx.Reader(), f.id)
			if err != nil {
				return err
			}
			if f.checks == nil {
				f.checks = []string{}
			}
			alreadyProved, err := fixerProvedAfter(tx.Reader(), f.id, f.seen)
			if err != nil {
				return err
			}
			if keep {
				if !alreadyProved {
					if err := appendEffect(tx, FixerProvedKind, f.id, fixerProof{FixerItem: f.id, Green: f.proof.commit, ProvedAt: f.proof.provedAt.UTC().Format("2006-01-02T15:04:05.000Z"), Checks: f.checks}, at); err != nil {
						return err
					}
					l.reportf("loop: %s proved by rerun (%s), keeping live run to finish\n", f.id, reason)
				}
				continue
			}
			if _, err := item.SetStateWithReceipt(ctx, tx, f.id, StateResolvedElsewhere, at, item.MoveReceipt{Reason: reason, By: Utility, ResolvesVia: "commit:" + f.proof.commit}); err != nil {
				return err
			}
			if !alreadyProved {
				if err := appendEffect(tx, FixerProvedKind, f.id, fixerProof{FixerItem: f.id, Green: f.proof.commit, ProvedAt: f.proof.provedAt.UTC().Format("2006-01-02T15:04:05.000Z"), Checks: f.checks}, at); err != nil {
					return err
				}
			}
			l.reportf("loop: %s resolved: %s\n", f.id, reason)
		}
		return nil
	})
}

// fixerProvedGreen answers the green commit a FixerProvedKind event recorded for a
// fixer, or "" when no proof resolved it.
func fixerProvedGreen(r *store.Reader, fixer string) (string, error) {
	var raw []byte
	err := r.QueryRow(`SELECT payload FROM events WHERE kind=? AND object_id=? ORDER BY seq DESC LIMIT 1`, FixerProvedKind, fixer).Scan(&raw)
	if errors.Is(err, sql.ErrNoRows) {
		return "", nil
	}
	if err != nil {
		return "", err
	}
	var p fixerProof
	if err := json.Unmarshal(raw, &p); err != nil {
		return "", err
	}
	return p.Green, nil
}

// fixerProvedAfter answers whether a FixerProvedKind event was already recorded for
// fixer at or after seen.
func fixerProvedAfter(r *store.Reader, fixer string, seen int64) (bool, error) {
	var ok bool
	err := r.QueryRow(`SELECT EXISTS(SELECT 1 FROM events WHERE kind=? AND object_id=? AND ts>=?)`, FixerProvedKind, fixer, seen).Scan(&ok)
	return ok, err
}

// fixerSeen answers the timestamp of the fixer's latest red observation (filing or a
// newer red attachment).
func fixerSeen(r *store.Reader, fixer string) (int64, error) {
	var seen sql.NullInt64
	if err := r.QueryRow(`SELECT MAX(ts) FROM events WHERE object_id=? AND kind IN (?, ?)`, fixer, item.AddKind, FixerAttachedKind).Scan(&seen); err != nil {
		return 0, err
	}
	return seen.Int64, nil
}

// fixerProvedProof answers the latest FixerProvedKind recorded for fixer at or after its
// latest red observation, or nil when none exists.
func fixerProvedProof(r *store.Reader, fixer string) (*fixerProof, error) {
	seen, err := fixerSeen(r, fixer)
	if err != nil {
		return nil, err
	}
	var raw []byte
	err = r.QueryRow(`SELECT payload FROM events WHERE kind=? AND object_id=? AND ts>=? ORDER BY seq DESC LIMIT 1`, FixerProvedKind, fixer, seen).Scan(&raw)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var p fixerProof
	if err := json.Unmarshal(raw, &p); err != nil {
		return nil, err
	}
	return &p, nil
}

// fixerProvedGreenAfterSeen answers the green commit a FixerProvedKind event recorded at
// or after the fixer's latest red observation, or "" when none exists.
func fixerProvedGreenAfterSeen(r *store.Reader, fixer string) (string, error) {
	p, err := fixerProvedProof(r, fixer)
	if err != nil || p == nil {
		return "", err
	}
	return p.Green, nil
}

// readIntermittentFixer answers whether a fixer has a FixerProvedKind record at or after
// its latest red observation (a rerun passed its checks) and the checks named in that proof.
func readIntermittentFixer(r *store.Reader, fixer string) (bool, []string, error) {
	p, err := fixerProvedProof(r, fixer)
	if err != nil || p == nil {
		return false, nil, err
	}
	return true, p.Checks, nil
}

// resolveKeptFixerWithoutCommit moves a proved trunk fixer whose run ended with no commit
// (headSHA == baseSHA) immediately to StateResolvedElsewhere (resolves_via commit:<proof>).
// It returns false when the fixer is not open or has no current proof.
func (l *Loop) resolveKeptFixerWithoutCommit(ctx context.Context, fixerID string) (bool, error) {
	if !IsTrunkFixer(fixerID) || l.cfg.Store == "" {
		return false, nil
	}
	s, err := store.Open(ctx, l.cfg.Store, true)
	if err != nil {
		return false, err
	}
	defer s.Close()
	resolved := false
	at := l.cfg.Now().UTC()
	err = s.WriteTx(ctx, func(tx *store.Tx) error {
		r := tx.Reader()
		lifecycle, err := definition.ForReader(r)
		if err != nil {
			return err
		}
		var state string
		if err := r.QueryRow(`SELECT state FROM items WHERE item_id=?`, fixerID).Scan(&state); err != nil {
			if errors.Is(err, sql.ErrNoRows) {
				return nil
			}
			return err
		}
		if finishedState(lifecycle.Parsed, state) {
			return nil
		}
		proof, err := fixerProvedProof(r, fixerID)
		if err != nil || proof == nil || proof.Green == "" {
			return err
		}
		reason := fmt.Sprintf("reran green on %s with no commit needed (%s)", shortSHA(proof.Green), strings.Join(proof.Checks, ", "))
		if _, err := item.SetStateWithReceipt(ctx, tx, fixerID, StateResolvedElsewhere, at, item.MoveReceipt{
			Reason:      reason,
			By:          Utility,
			ResolvesVia: "commit:" + proof.Green,
		}); err != nil {
			return err
		}
		resolved = true
		l.reportf("loop: %s resolved: %s\n", fixerID, reason)
		return nil
	})
	return resolved, err
}

// fixerKeepsLive answers whether an open fixer has an active claim/lease/dispatch, a
// live or unexamined run, or a committed candidate in flight (awaiting examination, or
// returning from a conflict or judge refusal), so resolveProvedFixers lets it finish
// instead of closing it.
func fixerKeepsLive(r *store.Reader, fixerID string) (bool, error) {
	hasReadOnly, err := tableExists(r, "read_only_runs")
	if err != nil {
		return false, err
	}
	if hasReadOnly {
		var exists bool
		if err := r.QueryRow(`SELECT EXISTS(SELECT 1 FROM read_only_runs WHERE item_id=? AND settled=0)`, fixerID).Scan(&exists); err != nil {
			return false, err
		}
		if exists {
			return true, nil
		}
	}
	hasNodes, err := tableExists(r, "node_runs")
	if err != nil {
		return false, err
	}
	if hasNodes {
		var exists bool
		if err := r.QueryRow(`SELECT EXISTS(SELECT 1 FROM node_runs WHERE item_id=? AND outcome='running')`, fixerID).Scan(&exists); err != nil {
			return false, err
		}
		if exists {
			return true, nil
		}
	}
	hasDispatches, err := tableExists(r, "dispatches")
	if err != nil {
		return false, err
	}

	// Any leased lane whose run_id belongs to this fixer (including run.allocate leases
	// before runs is written, and -judge leases) keeps the fixer live.
	laneRows, err := r.Query(`SELECT run_id FROM lanes WHERE state='leased' AND run_id IS NOT NULL`)
	if err != nil {
		return false, err
	}
	var leasedRuns []string
	for laneRows.Next() {
		var runID string
		if err := laneRows.Scan(&runID); err != nil {
			laneRows.Close()
			return false, err
		}
		leasedRuns = append(leasedRuns, runID)
	}
	if err := laneRows.Err(); err != nil {
		laneRows.Close()
		return false, err
	}
	laneRows.Close()
	for _, runID := range leasedRuns {
		belongs, err := runBelongsToItem(r, runID, fixerID, hasReadOnly, hasNodes, hasDispatches)
		if err != nil {
			return false, err
		}
		if belongs {
			return true, nil
		}
	}

	// Any unexamined drain.started (including a run that just exited before Loop.settle
	// examines its commit) keeps the fixer live.
	var unexaminedStarted bool
	if err := r.QueryRow(
		`SELECT EXISTS(
			SELECT 1 FROM events e
			WHERE e.kind = ? AND e.object_type = 'run'
			  AND json_valid(e.payload) AND json_extract(e.payload, '$.decision.item_id') = ?
			  AND NOT EXISTS(SELECT 1 FROM events x WHERE x.kind = ? AND x.object_type = 'run' AND x.object_id = e.object_id)
		)`,
		dispatchStartedKind, fixerID, examinationDoneKind,
	).Scan(&unexaminedStarted); err != nil {
		return false, err
	}
	if unexaminedStarted {
		return true, nil
	}

	// Any active dispatch without a runs row or examinationDoneKind keeps the fixer live.
	if hasDispatches {
		var pendingDispatch bool
		if err := r.QueryRow(
			`SELECT EXISTS(
				SELECT 1 FROM dispatches d
				WHERE d.item_id = ? AND d.action IN ('dispatch', 'retry') AND d.run_id IS NOT NULL
				  AND NOT EXISTS(SELECT 1 FROM runs r WHERE r.run_id = d.run_id)
				  AND NOT EXISTS(SELECT 1 FROM events x WHERE x.kind = ? AND x.object_type = 'run' AND x.object_id = d.run_id)
			)`,
			fixerID, examinationDoneKind,
		).Scan(&pendingDispatch); err != nil {
			return false, err
		}
		if pendingDispatch {
			return true, nil
		}
	}

	var runID, state string
	var eventSeq int64
	err = r.QueryRow(
		`SELECT run_id, state, event_seq FROM runs WHERE item_id = ? ORDER BY started_at DESC, event_seq DESC, rowid DESC LIMIT 1`,
		fixerID,
	).Scan(&runID, &state, &eventSeq)
	if errors.Is(err, sql.ErrNoRows) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if !isTerminalRunState(state) {
		return true, nil
	}
	var resumed bool
	if err := r.QueryRow(
		`SELECT EXISTS(SELECT 1 FROM events WHERE kind = ? AND object_type = 'run' AND object_id = ? AND seq > ?)`,
		run.ResumeKind, runID, eventSeq,
	).Scan(&resumed); err != nil {
		return false, err
	}
	if resumed {
		return true, nil
	}
	var refusalRaw []byte
	err = r.QueryRow(
		`SELECT payload FROM events WHERE kind = ? AND (object_id = ? OR (json_valid(payload) AND json_extract(payload, '$.writer_run_id') = ?)) ORDER BY seq DESC LIMIT 1`,
		RefusalKind, runID, runID,
	).Scan(&refusalRaw)
	if err == nil {
		var p struct {
			BaseSHA string `json:"base_sha"`
			HeadSHA string `json:"head_sha"`
		}
		if err := json.Unmarshal(refusalRaw, &p); err != nil {
			return false, err
		}
		return p.HeadSHA != "" && p.BaseSHA != "" && p.HeadSHA != p.BaseSHA, nil
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return false, err
	}
	var done bool
	if err := r.QueryRow(
		`SELECT EXISTS(SELECT 1 FROM events WHERE kind = ? AND object_type = 'run' AND object_id = ?)`,
		examinationDoneKind, runID,
	).Scan(&done); err != nil {
		return false, err
	}
	if done {
		return false, nil
	}
	var candRaw []byte
	err = r.QueryRow(
		`SELECT payload FROM events WHERE kind IN (?, ?) AND object_type = 'run' AND object_id = ? ORDER BY seq DESC LIMIT 1`,
		candidateReadyKind, candidatePreparedKind, runID,
	).Scan(&candRaw)
	if errors.Is(err, sql.ErrNoRows) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	var c struct {
		BaseSHA string `json:"base_sha"`
		HeadSHA string `json:"head_sha"`
	}
	if err := json.Unmarshal(candRaw, &c); err != nil {
		return false, err
	}
	return c.HeadSHA != "" && c.BaseSHA != "" && c.HeadSHA != c.BaseSHA, nil
}
