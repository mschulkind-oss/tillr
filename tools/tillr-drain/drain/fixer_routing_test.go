// fixerRoutingFixture is a document-fed store (one declared item) with a trunk fixer the
// loop filed against a real red commit, which is how the 2026-11-18 drain held 21 items.
func fixerRoutingFixture(t *testing.T) (refusalLoopFixture, *Loop, string, string) {
	t.Helper()
	f, l := passFixture(t, "item-declared", "item-spare")
	if err := os.MkdirAll(filepath.Join(f.root, "docs"), 0755); err != nil {
		t.Fatal(err)
	}
	writeForkFile(t, filepath.Join(f.root, "docs/request.md"), triageBlock+"\n"+strings.NewReplacer("item-declared", "item-spare", "Add the requested feature", "Add the spare feature").Replace(triageBlock))
	runGit(t, f.root, "add", "docs")
	runGit(t, f.root, "commit", "-qm", "declare the items")
	red := runGit(t, f.root, "rev-parse", TrunkRef)
	fixtureWrite(t, f, func(tx *store.Tx) error {
		_, err := tx.Exec(`UPDATE items SET seat='build', body_ref='docs/request.md#' || item_id`)
		return err
	})
	l.cfg.Policy.Seats = map[string]string{"build": "fixture", "design": "designer"}
	l.cfg.Policy.Backends["designer"] = Backend{Adapter: "fixture"}
	l.questions = &VantageQuestions{Root: f.root, Command: []string{"sh", "-c", "printf '%s' '{\"index\":{\"documents\":[]}}'"}}
	fixer, err := l.fileTrunkFixer(context.Background(), red, []string{"go-tool/unit"}, GateOutcome{SuspectPaths: []string{"base.txt"}})
	if err != nil {
		t.Fatal(err)
	}
	return f, l, fixer, red
}

func planFor(t *testing.T, l *Loop, id string) Decision {
	t.Helper()
	for _, p := range mustPlan(t, l) {
		if p.decision.ItemID == id {
			return p.decision
		}
	}
	t.Fatalf("no plan for %s", id)
	return Decision{}
}

// A fixer is generated by the loop and has no document. Document-fed triage must not
// treat it as an undeclared request and send it to the owner for one.
func TestTrunkFixerIsNeverTriagedForADocument(t *testing.T) {
	_, l, fixer, _ := fixerRoutingFixture(t)
	d := planFor(t, l, fixer)
	if d.Action != ActionDispatch || d.Seat != "build" || d.Reason == ReasonConflictOwner || d.Reason == ReasonTriageNoBlock || d.BlockConflict != nil {
		t.Fatalf("fixer was triaged instead of dispatched: %+v", d)
	}
	held := planFor(t, l, "item-declared")
	if held.Reason != ReasonTrunkBroken || held.DeferredBy != fixer {
		t.Fatalf("ordinary item not held behind the fixer: %+v", held)
	}
}

// A fixer an older build already parked on an owner triage conflict is returned to its
// worker: nothing in that conflict was the owner's to answer.
func TestFixerParkedOnTriageIsReturnedToItsWorker(t *testing.T) {
	ctx := context.Background()
	f, l, fixer, _ := fixerRoutingFixture(t)
	fixtureWrite(t, f, func(tx *store.Tx) error {
		return item.RecordConflict(tx, item.Conflict{
			ConflictID: "triage-" + fixer + "-v1", ItemID: fixer, TriageVersion: "v1", Status: "owner", WaitingOn: "owner",
			BlockedCriteria: []string{},
			Text:            "Request has no repository-relative Markdown document under docs/ in its body reference; sync reads only that document scope. The owner must supply one or close the item.",
		}, l.cfg.Now().UTC())
	})
	if err := l.releaseFixerTriage(ctx); err != nil {
		t.Fatal(err)
	}
	fixtureWrite(t, f, func(tx *store.Tx) error {
		var state string
		if err := tx.QueryRow(`SELECT state FROM items WHERE item_id=?`, fixer).Scan(&state); err != nil {
			return err
		}
		cs, err := item.ReadConflicts(tx.Reader())
		if err != nil {
			return err
		}
		if state != StateInQueue || cs[fixer].Status != "closed" || cs[fixer].WaitingOn == "owner" {
			t.Fatalf("fixer still parked: state=%s conflict=%+v", state, cs[fixer])
		}
		return nil
	})
	if d := planFor(t, l, fixer); d.Action != ActionDispatch || d.Seat != "build" {
		t.Fatalf("released fixer not dispatched: %+v", d)
	}
	// Idempotent: a second pass writes nothing.
	before := eventCount(t, f.storePath)
	if err := l.releaseFixerTriage(ctx); err != nil {
		t.Fatal(err)
	}
	if got := eventCount(t, f.storePath); got != before {
		t.Fatalf("second release wrote %d event(s)", got-before)
	}
}

// A blocked fixer reaches the owner only by an objection naming him. A report naming no
// actor goes back to the fixer's own worker with the rule it must follow.
func TestFixerBlockedReportReachesTheOwnerOnlyByName(t *testing.T) {
	for _, tc := range []struct {
		name, report, status, waiting, state string
	}{
		{"no actor", "Cannot see why the suite fails.\nRESULT: blocked", "answered", "build", StateInQueue},
		{"build", "Retrying is the next step.\nNEXT-ACTOR: build\nRESULT: blocked", "answered", "build", StateInQueue},
		{"owner", "Fix needs `tests/outside_test.go`, outside the fence.\nNEXT-ACTOR: owner\nRESULT: blocked", "owner", "owner", StateBlocked},
		{"fence obstacle", "OBSTACLE: fence\nPATHS: tests/outside_test.go\nEVIDENCE: the failing test lives there\nRESULT: blocked", "owner", "owner", StateBlocked},
		{"owner obstacle", "OBSTACLE: owner\nQUESTION: may the fixer skip the flaky check?\nRESULT: blocked", "owner", "owner", StateBlocked},
		{"incomplete obstacle", "OBSTACLE: fence\nRESULT: blocked", "answered", "build", StateInQueue},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f, l, fixer, _ := fixerRoutingFixture(t)
			d := Decision{ItemID: fixer, RunRequest: &run.Request{RunID: "fixer-run"}}
			if err := l.reportedBlock(context.Background(), d, tc.report); err != nil {
				t.Fatal(err)
			}
			fixtureWrite(t, f, func(tx *store.Tx) error {
				var state string
				if err := tx.QueryRow(`SELECT state FROM items WHERE item_id=?`, fixer).Scan(&state); err != nil {
					return err
				}
				cs, err := item.ReadConflicts(tx.Reader())
				if err != nil {
					return err
				}
				c := cs[fixer]
				if c.Status != tc.status || c.WaitingOn != tc.waiting || state != tc.state {
					t.Fatalf("report routed to %s/%s (item %s), want %s/%s (%s): %+v", c.Status, c.WaitingOn, state, tc.status, tc.waiting, tc.state, c)
				}
				if tc.waiting != "owner" && !strings.Contains(c.Text, "OBSTACLE: <kind>") {
					t.Fatalf("returned report does not state the obstacle contract: %q", c.Text)
				}
				// A generated repair has no block to widen, so its fence obstacle reaches the
				// owner as an explicit question naming the paths.
				if tc.name == "fence obstacle" && (!strings.Contains(c.Text, "Question for the owner") || !strings.Contains(c.Text, "tests/outside_test.go")) {
					t.Fatalf("the owner is not asked a question naming the paths: %q", c.Text)
				}
				return nil
			})
		})
	}
}

// writeGreenProof moves the heavy pointer and records its proof the way the heavy runner
// does after a green run.
func writeGreenProof(t *testing.T, l *Loop, sha string, at time.Time, passed []string) {
	t.Helper()
	runGit(t, l.cfg.Root, "update-ref", GreenRef, sha)
	dir, err := heavyDirectory(context.Background(), l.cfg.Root)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(dir, 0755); err != nil {
		t.Fatal(err)
	}
	if err := publishHeavyJSON(dir, "green-"+sha+".json", heavy.GreenProof{Commit: sha, ProvedAt: at, Passed: passed}); err != nil {
		t.Fatal(err)
	}
}

func fixerState(t *testing.T, f refusalLoopFixture, id string) string {
	t.Helper()
	var state string
	fixtureWrite(t, f, func(tx *store.Tx) error {
		return tx.QueryRow(`SELECT state FROM items WHERE item_id=?`, id).Scan(&state)
	})
	return state
}

// A green heavy proof of a tip containing the red commit, recorded after the fixer's last
// red observation and passing the fixer's checks, releases every trunk-broken hold —
// whatever the fixer's own state, including parked on the owner.
func TestGreenProofResolvesTheFixerAndReleasesTrunkBrokenHolds(t *testing.T) {
	ctx := context.Background()
	f, l, fixer, red := fixerRoutingFixture(t)
	// Park the fixer on an explicit owner objection: the proof must still resolve it.
	if err := l.reportedBlock(ctx, Decision{ItemID: fixer, RunRequest: &run.Request{RunID: "fixer-run"}}, "needs a ruling\nNEXT-ACTOR: owner\nRESULT: blocked"); err != nil {
		t.Fatal(err)
	}
	// An acquittal behind the same fixer is released by the same proof.
	fixtureWrite(t, f, func(tx *store.Tx) error {
		_, err := item.SetState(ctx, tx, "item-spare", StateBlocked, l.cfg.Now(), item.WaitingOn{Waiter: "item:" + fixer, Reason: RefusalTrunkAlreadyRed + ": go-tool/unit"})
		return err
	})
	runGit(t, f.root, "commit", "--allow-empty", "-qm", "repair lands")
	tip := runGit(t, f.root, "rev-parse", TrunkRef)
	later := l.cfg.Now().UTC().Add(time.Minute)

	// Not yet evidence: a proof older than the red observation, a proof that did not
	// pass the fixer's check, and a proof not containing the red commit.
	writeGreenProof(t, l, tip, l.cfg.Now().UTC().Add(-time.Minute), []string{"go-tool/unit"})
	if err := l.resolveProvedFixers(ctx); err != nil {
		t.Fatal(err)
	}
	if got := fixerState(t, f, fixer); got != StateBlocked {
		t.Fatalf("a proof older than the red resolved the fixer: %s", got)
	}
	writeGreenProof(t, l, tip, later, []string{"go-tool/other"})
	if err := l.resolveProvedFixers(ctx); err != nil {
		t.Fatal(err)
	}
	if got := fixerState(t, f, fixer); got != StateBlocked {
		t.Fatalf("a proof without the fixer's check resolved it: %s", got)
	}
	base := runGit(t, f.root, "rev-parse", red+"^")
	writeGreenProof(t, l, base, later, []string{"go-tool/unit"})
	if err := l.resolveProvedFixers(ctx); err != nil {
		t.Fatal(err)
	}
	if got := fixerState(t, f, fixer); got != StateBlocked {
		t.Fatalf("a proof below the red commit resolved the fixer: %s", got)
	}
	if held := planFor(t, l, "item-declared"); held.Reason != ReasonTrunkBroken {
		t.Fatalf("hold released without proof: %+v", held)
	}

	writeGreenProof(t, l, tip, later, []string{"go-tool/unit", "go-tool/other"})
	if err := l.resolveProvedFixers(ctx); err != nil {
		t.Fatal(err)
	}
	if got := fixerState(t, f, fixer); got != StateResolvedElsewhere {
		t.Fatalf("green proof did not resolve the fixer: %s", got)
	}
	if err := l.releaseTrunkAcquittals(ctx); err != nil {
		t.Fatal(err)
	}
	if got := fixerState(t, f, "item-spare"); got != StateInQueue {
		t.Fatalf("acquittal behind the proved fixer not released: %s", got)
	}
	for _, id := range []string{"item-declared", "item-spare"} {
		if d := planFor(t, l, id); d.Reason == ReasonTrunkBroken {
			t.Fatalf("%s still held trunk-broken on a proved trunk: %+v", id, d)
		}
	}
}

// The green proof names the checks it passed, which is what lets a fixer be resolved by
// it; an unavailable check is not a pass and is not named.
func TestHeavyGreenProofNamesItsPassedChecks(t *testing.T) {
	root, base := heavyRepo(t)
	heavyGit(t, root, "update-ref", GreenRef, base)
	tip := heavyCommit(t, root, "next")
	runner := heavyFixture(t, root, func(context.Context, string, string) ([]HeavyCheck, error) {
		return []HeavyCheck{{CheckID: "unit", Result: "pass"}, {CheckID: "web", Result: "unavailable"}}, nil
	})
	if _, err := runner.Run(context.Background()); err != nil {
		t.Fatal(err)
	}
	proof, err := readGreenProof(context.Background(), root)
	if err != nil {
		t.Fatal(err)
	}
	if proof.Commit != tip || strings.Join(proof.Passed, ",") != "unit" {
		t.Fatalf("proof = %+v, want %s passing only unit", proof, tip)
	}
}

// writeTipProgress records the tip run's per-check passes the way the heavy runner and the
// legacy program's adapter do while a run is still going.
func writeTipProgress(t *testing.T, l *Loop, tip string, passed map[string]time.Time, legacy map[string]time.Time) {
	t.Helper()
	dir, err := heavyDirectory(context.Background(), l.cfg.Root)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(dir, 0755); err != nil {
		t.Fatal(err)
	}
	p := heavyProgress{TipSHA: tip, Checks: map[string]HeavyCheck{}, PassedAt: map[string]time.Time{}}
	for id, at := range passed {
		p.Checks[id] = HeavyCheck{CheckID: id, Result: "pass"}
		p.PassedAt[id] = at
	}
	if err := publishHeavyJSON(dir, "heavy-progress.json", p); err != nil {
		t.Fatal(err)
	}
	checks := map[string]map[string]any{}
	for id, at := range legacy {
		checks[id] = map[string]any{"seconds": 1, "proved_at": at.UTC().Format(time.RFC3339)}
	}
	if err := publishHeavyJSON(dir, "heavy-legacy-progress.json", map[string]any{"tip_sha": tip, "checks": checks, "reused": []string{}}); err != nil {
		t.Fatal(err)
	}
}

// A stale fixer — its named check already passes on a tip that contains its red commit —
// is resolved by that one recorded pass, while the rest of the tip run is still going or
// is red for another check. This is the 2026-11-18 fixer-main-8ab93d9ace80, dispatched
// seven times while the tip run had already passed its check and no whole run could be
// green.
func TestTipRunPassOfTheFixersCheckResolvesAStaleFixer(t *testing.T) {
	ctx := context.Background()
	f, l, fixer, red := fixerRoutingFixture(t)
	report := &strings.Builder{}
	l.cfg.Report = report
	fixtureWrite(t, f, func(tx *store.Tx) error {
		_, err := item.SetState(ctx, tx, "item-spare", StateBlocked, l.cfg.Now(), item.WaitingOn{Waiter: "item:" + fixer, Reason: RefusalTrunkAlreadyRed + ": go-tool/unit"})
		return err
	})
	runGit(t, f.root, "commit", "--allow-empty", "-qm", "repair lands")
	tip := runGit(t, f.root, "rev-parse", TrunkRef)
	before, later := l.cfg.Now().UTC().Add(-time.Minute), l.cfg.Now().UTC().Add(time.Minute)

	// Not evidence: another check's pass, a pass older than the red observation, and a
	// pass on a commit that does not contain the red commit.
	for _, tc := range []struct {
		name   string
		commit string
		legacy map[string]time.Time
	}{
		{"another check", tip, map[string]time.Time{"go-tool/other": later}},
		{"older than the red", tip, map[string]time.Time{"go-tool/unit": before}},
		{"below the red commit", runGit(t, f.root, "rev-parse", red+"^"), map[string]time.Time{"go-tool/unit": later}},
	} {
		writeTipProgress(t, l, tc.commit, nil, tc.legacy)
		if err := l.resolveProvedFixers(ctx); err != nil {
			t.Fatal(err)
		}
		if got := fixerState(t, f, fixer); got == StateResolvedElsewhere {
			t.Fatalf("%s resolved the fixer", tc.name)
		}
	}

	// The tip run passed the fixer's check (recorded by the legacy adapter) and failed
	// another: no green proof exists, and the fixer is resolved anyway.
	writeTipProgress(t, l, tip, map[string]time.Time{"go-tool/other": later}, map[string]time.Time{"go-tool/unit": later})
	if err := l.resolveProvedFixers(ctx); err != nil {
		t.Fatal(err)
	}
	if got := fixerState(t, f, fixer); got != StateResolvedElsewhere {
		t.Fatalf("a tip pass of the fixer's check did not resolve it: %s", got)
	}
	if err := l.releaseTrunkAcquittals(ctx); err != nil {
		t.Fatal(err)
	}
	if got := fixerState(t, f, "item-spare"); got != StateInQueue {
		t.Fatalf("acquittal behind the resolved fixer not released: %s", got)
	}
	if d := planFor(t, l, "item-declared"); d.Reason == ReasonTrunkBroken {
		t.Fatalf("still held trunk-broken: %+v", d)
	}
	if out := report.String(); !strings.Contains(out, fixer+" resolved: the heavy run of "+tip) {
		t.Fatalf("log lacks the resolution: %s", out)
	}
}

// A generated repair that ends blocked twice on the same trunk with the same obstacle is
// an identical repeat, however its report is worded: the second goes to the owner with
// the loop's own question rather than back to its worker. A moved trunk is a new obstacle.
func TestGeneratedRepairBlockedTheSameWayTwiceGoesToTheOwner(t *testing.T) {
	ctx := context.Background()
	f, l, fixer, _ := fixerRoutingFixture(t)
	report := &strings.Builder{}
	l.cfg.Report = report
	waiting := func(run string) item.Conflict {
		t.Helper()
		var c item.Conflict
		fixtureWrite(t, f, func(tx *store.Tx) error {
			all, err := item.ReadConflicts(tx.Reader())
			c = all[fixer]
			return err
		})
		if c.ConflictID != "conflict-"+run {
			t.Fatalf("latest conflict %s, want conflict-%s", c.ConflictID, run)
		}
		return c
	}
	block := func(runID, text string) item.Conflict {
		t.Helper()
		if err := l.reportedBlock(ctx, Decision{ItemID: fixer, RunRequest: &run.Request{RunID: runID}}, text+"\nRESULT: blocked"); err != nil {
			t.Fatal(err)
		}
		return waiting(runID)
	}
	if c := block("fixer-a1", "The repair is already an ancestor of the staged base."); c.WaitingOn != "build" {
		t.Fatalf("first blocked report: %+v", c)
	}
	c := block("fixer-a2", "**Blocker:** the named tip is red, but its repair is already in my base; I stopped.")
	if c.WaitingOn != "owner" || !strings.Contains(c.Text, "exactly as run fixer-a1 did") {
		t.Fatalf("an identical repeat went back to its worker: %+v", c)
	}
	if !strings.Contains(report.String(), fixer+" ended blocked as run fixer-a1 did") {
		t.Fatalf("log: %s", report.String())
	}
	runGit(t, f.root, "commit", "--allow-empty", "-qm", "the trunk moves")
	if c := block("fixer-a3", "The repair is already an ancestor of the staged base."); c.WaitingOn != "build" {
		t.Fatalf("a block on a moved trunk is not a repeat: %+v", c)
	}
}
