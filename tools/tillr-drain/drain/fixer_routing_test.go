// fixerRoutingFixture is a document-fed store (one declared item) with a trunk fixer the
// loop filed against a real red commit, which is how the 2026-11-18 drain held 21 items.
func fixerRoutingFixture(t *testing.T) (refusalLoopFixture, *Loop, string, string) {
	t.Helper()
	f, l := passFixture(t, "item-declared", "item-spare")
	if err := os.MkdirAll(filepath.Join(f.root, "docs"), 0755); err != nil {
		t.Fatal(err)
	}
	writeForkFile(t, filepath.Join(f.root, "docs/request.md"), triageBlock+"\n"+strings.NewReplacer("item-declared", "item-spare", "Add the requested feature", "Add the spare feature").Replace(triageBlock))
	runGit(t, f.root, "add", "docs")
	runGit(t, f.root, "commit", "-qm", "declare the items")
	red := runGit(t, f.root, "rev-parse", TrunkRef)
	fixtureWrite(t, f, func(tx *store.Tx) error {
		_, err := tx.Exec(`UPDATE items SET seat='build', body_ref='docs/request.md#' || item_id`)
		return err
	})
	l.cfg.Policy.Seats = map[string]string{"build": "fixture", "design": "designer"}
	l.cfg.Policy.Backends["designer"] = Backend{Adapter: "fixture"}
	l.questions = &VantageQuestions{Root: f.root, Command: []string{"sh", "-c", "printf '%s' '{\"index\":{\"documents\":[]}}'"}}
	fixer, err := l.fileTrunkFixer(context.Background(), red, []string{"go-tool/unit"}, GateOutcome{SuspectPaths: []string{"base.txt"}})
	if err != nil {
		t.Fatal(err)
	}
	return f, l, fixer, red
}

func planFor(t *testing.T, l *Loop, id string) Decision {
	t.Helper()
	for _, p := range mustPlan(t, l) {
		if p.decision.ItemID == id {
			return p.decision
		}
	}
	t.Fatalf("no plan for %s", id)
	return Decision{}
}

// A fixer is generated by the loop and has no document. Document-fed triage must not
// treat it as an undeclared request and send it to the owner for one. Under OQ-GP7,
// an ordinary item in-queue is not held by an open fixer and dispatches too.
func TestTrunkFixerIsNeverTriagedForADocument(t *testing.T) {
	_, l, fixer, _ := fixerRoutingFixture(t)
	d := planFor(t, l, fixer)
	if d.Action != ActionDispatch || d.Seat != "build" || d.Reason == ReasonConflictOwner || d.Reason == ReasonTriageNoBlock || d.BlockConflict != nil {
		t.Fatalf("fixer was triaged instead of dispatched: %+v", d)
	}
	ordinary := planFor(t, l, "item-declared")
	if ordinary.Action != ActionDispatch {
		t.Fatalf("ordinary item held behind open fixer under OQ-GP7: %+v", ordinary)
	}
}

// A fixer an older build already parked on an owner triage conflict is returned to its
// worker: nothing in that conflict was the owner's to answer.
func TestFixerParkedOnTriageIsReturnedToItsWorker(t *testing.T) {
	ctx := context.Background()
	f, l, fixer, _ := fixerRoutingFixture(t)
	fixtureWrite(t, f, func(tx *store.Tx) error {
		return item.RecordConflict(tx, item.Conflict{
			ConflictID: "triage-" + fixer + "-v1", ItemID: fixer, TriageVersion: "v1", Status: "owner", WaitingOn: "owner",
			BlockedCriteria: []string{},
			Text:            "Request has no repository-relative Markdown document under docs/ in its body reference; sync reads only that document scope. The owner must supply one or close the item.",
		}, l.cfg.Now().UTC())
	})
	if err := l.releaseGeneratedTriage(ctx); err != nil {
		t.Fatal(err)
	}
	fixtureWrite(t, f, func(tx *store.Tx) error {
		var state string
		if err := tx.QueryRow(`SELECT state FROM items WHERE item_id=?`, fixer).Scan(&state); err != nil {
			return err
		}
		cs, err := item.ReadConflicts(tx.Reader())
		if err != nil {
			return err
		}
		if state != StateInQueue || cs[fixer].Status != "closed" || cs[fixer].WaitingOn == "owner" {
			t.Fatalf("fixer still parked: state=%s conflict=%+v", state, cs[fixer])
		}
		return nil
	})
	if d := planFor(t, l, fixer); d.Action != ActionDispatch || d.Seat != "build" {
		t.Fatalf("released fixer not dispatched: %+v", d)
	}
	// Idempotent: a second pass writes nothing.
	before := eventCount(t, f.storePath)
	if err := l.releaseGeneratedTriage(ctx); err != nil {
		t.Fatal(err)
	}
	if got := eventCount(t, f.storePath); got != before {
		t.Fatalf("second release wrote %d event(s)", got-before)
	}
}

// A blocked fixer reaches the owner only by an objection naming him. A report naming no
// actor goes back to the fixer's own worker with the rule it must follow.
func TestFixerBlockedReportReachesTheOwnerOnlyByName(t *testing.T) {
	for _, tc := range []struct {
		name, report, status, waiting, state string
	}{
		{"no actor", "Cannot see why the suite fails.\nRESULT: blocked", "answered", "build", StateInQueue},
		{"build", "Retrying is the next step.\nNEXT-ACTOR: build\nRESULT: blocked", "answered", "build", StateInQueue},
		{"owner", "Fix needs `tests/outside_test.go`, outside the fence.\nNEXT-ACTOR: owner\nRESULT: blocked", "owner", "owner", StateBlocked},
		{"retired fence obstacle", "OBSTACLE: fence\nPATHS: tests/outside_test.go\nEVIDENCE: the failing test lives there\nRESULT: blocked", "answered", "build", StateInQueue},
		{"owner obstacle", "OBSTACLE: owner\nQUESTION: may the fixer skip the flaky check?\nRESULT: blocked", "owner", "owner", StateBlocked},
		{"incomplete obstacle", "OBSTACLE: fence\nRESULT: blocked", "answered", "build", StateInQueue},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f, l, fixer, _ := fixerRoutingFixture(t)
			d := Decision{ItemID: fixer, RunRequest: &run.Request{RunID: "fixer-run"}}
			if err := l.reportedBlock(context.Background(), d, tc.report); err != nil {
				t.Fatal(err)
			}
			fixtureWrite(t, f, func(tx *store.Tx) error {
				var state string
				if err := tx.QueryRow(`SELECT state FROM items WHERE item_id=?`, fixer).Scan(&state); err != nil {
					return err
				}
				cs, err := item.ReadConflicts(tx.Reader())
				if err != nil {
					return err
				}
				c := cs[fixer]
				if c.Status != tc.status || c.WaitingOn != tc.waiting || state != tc.state {
					t.Fatalf("report routed to %s/%s (item %s), want %s/%s (%s): %+v", c.Status, c.WaitingOn, state, tc.status, tc.waiting, tc.state, c)
				}
				if tc.waiting != "owner" && !strings.Contains(c.Text, "OBSTACLE: <kind>") {
					t.Fatalf("returned report does not state the obstacle contract: %q", c.Text)
				}
				return nil
			})
		})
	}
}

// writeGreenProof moves the heavy pointer and records its proof the way the heavy runner
// does after a green run.
func writeGreenProof(t *testing.T, l *Loop, sha string, at time.Time, passed []string) {
	t.Helper()
	runGit(t, l.cfg.Root, "update-ref", GreenRef, sha)
	dir, err := heavyDirectory(context.Background(), l.cfg.Root)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(dir, 0755); err != nil {
		t.Fatal(err)
	}
	if err := publishHeavyJSON(dir, "green-"+sha+".json", heavy.GreenProof{Commit: sha, ProvedAt: at, Passed: passed}); err != nil {
		t.Fatal(err)
	}
}

