// resolveCommit answers the full sha a fixer id's short sha names, or "" when the
// repository holds no such commit.
func resolveCommit(ctx context.Context, root, sha string) (string, error) {
	cmd := exec.CommandContext(ctx, "git", "-C", root, "rev-parse", "--verify", "--quiet", sha+"^{commit}")
	out, err := cmd.Output()
	if err == nil {
		return strings.TrimSpace(string(out)), nil
	}
	var exit *exec.ExitError
	if errors.As(err, &exit) && exit.ExitCode() == 1 {
		return "", nil
	}
	return "", Externalf("resolving fixer commit %s: %v", sha, err)
}

// provedFixer is one open fixer a proof covers, and the proof that covers it.
type provedFixer struct {
	id       string
	seen     int64
	checks   []string
	proof    checkProof
	finished bool
	keepLive bool
}

func provableChecks(checks []string) []string {
	return fixer.ProvableChecks(checks)
}

// awaitedFixers answers the trunk fixers some blocked item waits on as a
// trunk-already-red acquittal.
func awaitedFixers(r *store.Reader) (map[string]bool, error) {
	rows, err := r.Query(`SELECT item_id FROM items WHERE state=?`, StateBlocked)
	if err != nil {
		return nil, err
	}
	ids := []string{}
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			rows.Close()
			return nil, err
		}
		ids = append(ids, id)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return nil, err
	}
	awaited := map[string]bool{}
	for _, id := range ids {
		waiting, _, err := item.ReadWaitingOn(r, id)
		if err != nil {
			return nil, err
		}
		if waiting == nil {
			continue
		}
		if fixer := strings.TrimPrefix(waiting.Waiter, "item:"); fixer != waiting.Waiter && IsTrunkFixer(fixer) {
			awaited[fixer] = true
		}
	}
	return awaited, nil
}

type checkProof = fixer.CheckProof

// proofPastRed answers whether proofCommit is at or past red on the trunk. On an
// unrewritten trunk (or one whose rewrite is in trunk_rewrites), containsCommit answers
// directly. When the trunk was rewritten off red without a trunk_rewrites row (for
// instance, an earlier accept-rewrite onto a moved base), red's patch-matched commit on
// the trunk must be an ancestor of proofCommit; if red was dropped or amended off an
// accepted trunk, proofCommit must contain their merge base.
func proofPastRed(ctx context.Context, root, lost, red, proofCommit string) (bool, error) {
	ok, err := containsCommit(ctx, root, red, proofCommit)
	if err != nil || ok {
		return ok, err
	}
	onTrunk, err := containsCommit(ctx, root, red, TrunkRef)
	if err != nil || onTrunk {
		return false, err
	}
	proofOnTrunk, err := containsCommit(ctx, root, proofCommit, TrunkRef)
	if err != nil || !proofOnTrunk {
		return false, err
	}
	out, err := gather(ctx, gitKey("past-red", root, []string{red, proofCommit, lost}), func(ctx context.Context) (string, error) {
		_, oldIDs, err := patchIDs(ctx, root, TrunkRef+".."+red)
		if err != nil {
			return "", err
		}
		newCommits, newIDs, err := patchIDs(ctx, root, red+".."+TrunkRef)
		if err != nil {
			return "", err
		}
		if id := oldIDs[red]; id != "" {
			for _, c := range newCommits {
				if newIDs[c] == id {
					yes, err := trunkAncestor(ctx, root, c, proofCommit)
					if err != nil || !yes {
						return "no", err
					}
					return "yes", nil
				}
			}
		}
		if lost != "" {
			return "no", nil
		}
		mb, err := rawGit(ctx, root, nil, "merge-base", red, TrunkRef)
		if err != nil {
			return "no", nil
		}
		yes, err := trunkAncestor(ctx, root, strings.TrimSpace(mb), proofCommit)
		if err != nil || !yes {
			return "no", err
		}
		return "yes", nil
	})
	return out == "yes", err
}

